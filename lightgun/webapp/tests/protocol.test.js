test('device events are delivered while docked and during record streams', async () => {
    const ctx = await setup();
    try {
        assert.equal((await ctx.protocol.getSettings()).ok, true);
        ctx.firmware.queueEvent(C.sBtnPressed, Uint8Array.of(2));
        ctx.firmware.queueEvent(C.sTemperatureUpd, Uint8Array.of(41));
        assert.ok(await waitUntil(() => ctx.events.length >= 2));
        assert.deepEqual(ctx.events.slice(0, 2), [
            { command: C.sBtnPressed, payload: [2] },
            { command: C.sTemperatureUpd, payload: [41] }
        ]);

        // An event injected in the middle of a record stream must not break it.
        const original = ctx.firmware.sendResponse.bind(ctx.firmware);
        let injected = false;
        ctx.firmware.sendResponse = async (command, payload, final) => {
            if (!injected && command === C.sGetSettings) {
                injected = true;
                ctx.firmware.sendEvent(C.sBtnReleased, Uint8Array.of(2));
            }
            return original(command, payload, final);
        };
        const again = await redock(ctx);
        assert.equal(again.ok, true);
        assert.ok(await waitUntil(() => ctx.events.some((e) => e.command === C.sBtnReleased)));
    } finally {
        await teardown(ctx);
    }
});

