// ===== Robustness ==========================================================

test('lost ACKs and duplicate retransmissions are handled on both sides', async () => {
    const ctx = await setup();
    try {
        // Drop the App's first ACK for every record of sGetSettings: the firmware
        // retransmits the same frame, which the App must ACK again but ignore.
        const droppedAcks = new Set();
        ctx.link.filterToFirmware = (bytes) => {
            if (bytes.length === 7 && (bytes[2] & 3) === 3 && bytes[3] === C.sGetSettings) {
                const key = bytes[4];
                if (!droppedAcks.has(key)) { droppedAcks.add(key); return null; }
            }
            return bytes;
        };
        // Drop the firmware's first ACK for sCommitStart: the App retransmits.
        let droppedStartAck = false;
        ctx.link.filterToApp = (bytes) => {
            if (!droppedStartAck && bytes.length === 7 && (bytes[2] & 3) === 3 && bytes[3] === C.sCommitStart) {
                droppedStartAck = true;
                return null;
            }
            return bytes;
        };

        const loaded = await ctx.protocol.getSettings();
        assert.equal(loaded.ok, true);
        assert.ok(droppedAcks.size > 5);
        assert.equal(loaded.config.settings[S.settingsTypes_e.solenoidOffLength], 80);

        const result = await ctx.protocol.commitSettings(ctx.protocol.codec.cloneConfig(loaded.config), loaded.config);
        assert.equal(result.ok, true);
        assert.equal(droppedStartAck, true);
    } finally {
        await teardown(ctx);
    }
});

