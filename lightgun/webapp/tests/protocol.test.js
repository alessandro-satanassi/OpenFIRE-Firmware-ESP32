/*  OpenFIRE Web App: protocol tests against the mock firmware.

    Run from lightgun/webapp:   node --test tests/*.test.js
    Requires boards/OpenFIREshared.js generated by scripts/build_shared_js.py
    (a normal PlatformIO build regenerates it).
*/
'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const { MockFirmware, MemoryLink, createMemoryTransport, crc8 } = require('./mock-firmware.js');

const WEBAPP = path.join(__dirname, '..');

function loadScript(relative) {
    vm.runInThisContext(fs.readFileSync(path.join(WEBAPP, relative), 'utf8'), { filename: relative });
}

loadScript('boards/OpenFIREshared.js');
vm.runInThisContext('globalThis.OpenFIREshared = OpenFIREshared;');
loadScript('js/core/transport.js');
loadScript('js/core/protocol.js');

const OF = globalThis.OF;
const S = globalThis.OpenFIREshared;
const C = S.serialCmdTypes_e;

if (!S.boolTypes_Strings)
    throw new Error('boards/OpenFIREshared.js is outdated: regenerate it with scripts/build_shared_js.py');

// Quiet expected warnings; keep them available with OF_TEST_VERBOSE=1.
if (!process.env.OF_TEST_VERBOSE) {
    console.warn = () => {};
    console.debug = () => {};
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function setup(linkOptions = {}, firmwareOptions = {}) {
    const link = new MemoryLink(linkOptions);
    const firmware = new MockFirmware(S, link, firmwareOptions);
    firmware.start();
    const protocol = new OF.Protocol({ shared: S });
    const events = [];
    protocol.on('event', (command, payload) => events.push({ command, payload: Array.from(payload) }));
    const closed = [];
    protocol.on('closed', (reason) => closed.push(reason));
    const transport = createMemoryTransport(OF, link);
    await protocol.connect(transport);
    return { link, firmware, protocol, transport, events, closed };
}

async function teardown(ctx) {
    ctx.link.connected = false;
    await ctx.firmware.stop();
    if (ctx.transport.isOpen)
        await ctx.transport.close();
}

// The firmware ignores a new dock while a session is active (as with the Qt App,
// which always disconnects and reopens the port before docking again).
async function redock(ctx) {
    await ctx.protocol.disconnect();
    const transport = createMemoryTransport(OF, ctx.link);
    ctx.transport = transport;
    await ctx.protocol.connect(transport);
    return ctx.protocol.getSettings();
}

async function waitUntil(predicate, timeoutMs = 3000) {
    const started = Date.now();
    while (!predicate()) {
        if (Date.now() - started > timeoutMs)
            return false;
        await sleep(5);
    }
    return true;
}

