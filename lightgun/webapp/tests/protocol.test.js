test('frame encoding matches the firmware CRC-8 and layout', () => {
    const payload = Uint8Array.from([0x52, 0x75, 0x6D, 0x62, 0x00, 0x01, 0x01]);
    const frame = OF.ProtocolUtils.buildFrame(0x00, C.sCommitToggles, 7, payload);
    assert.equal(frame[0], 0xA5);
    assert.equal(frame[1], 0x5A);
    assert.equal(frame[3], C.sCommitToggles);
    assert.equal(frame[4], 7);
    assert.equal(frame[5], payload.length);
    assert.equal(frame[frame.length - 1], crc8(frame.subarray(2, frame.length - 1)));
    assert.equal(OF.ProtocolUtils.buildFrame(0, 1, 1, new Uint8Array(201)), null);
});

test('profile and TinyUSB codecs keep the C struct layout', () => {
    const codec = new OF.ProtocolCodec(S);
    const profile = Object.assign(codec.createProfile(), {
        topOffset: -12, TLled: 1023.5, irSensitivity: 2, color: 0x12AB34, name: 'Arcade Room CRT!!'
    });
    const raw = codec.encodeProfile(profile);
    assert.equal(raw.length, 68);
    const view = new DataView(raw.buffer);
    assert.equal(view.getInt32(0, true), -12);
    assert.equal(view.getFloat32(16, true), 1023.5);
    assert.equal(view.getUint32(32, true), 2);
    assert.equal(view.getUint32(48, true), 0x12AB34);
    assert.equal(OF.ProtocolUtils.decodeCString(raw.subarray(52)), 'Arcade Room CRT'); // 15 chars + NUL

    const usb = codec.encodeTinyUSB({ id: 0x1234, name: 'FIRECon P3' });
    assert.equal(usb.length, 18);
    assert.deepEqual(codec.decodeTinyUSB(usb), { id: 0x1234, name: 'FIRECon P3' });
});

